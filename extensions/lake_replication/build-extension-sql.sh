#!/bin/sh
set -eu

if [ "$#" -lt 1 ]; then
    echo "usage: $0 OUTPUT [MIGRATION ...]" >&2
    exit 2
fi

output=$1
shift
script_dir=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
migrations_dir="$script_dir/../../migrations"
temporary="$output.tmp"
trap 'rm -f "$temporary"' EXIT HUP INT TERM

if [ "$#" -eq 0 ]; then
    set -- "$migrations_dir"/[0-9][0-9][0-9][0-9]_*.sql
fi

case "$(basename -- "$output")" in
    *--*--*.sql) guard='ALTER EXTENSION lake_replication UPDATE' ;;
    *) guard='CREATE EXTENSION lake_replication' ;;
esac

{
    printf '\\echo Use "%s" to load this file. \\quit\n\n' "$guard"
    printf '%s\n' '-- Generated from migrations/*.sql; do not edit this file directly.'
    for migration in "$@"; do
        name=$(basename -- "$migration")
        printf '\n-- %s\n\n' "$name"
        awk '
            NR == 1 {
                if ($0 != "BEGIN;") {
                    print FILENAME ": expected BEGIN; on the first line" > "/dev/stderr"
                    exit 1
                }
                next
            }
            { lines[NR] = $0 }
            END {
                if ($0 != "COMMIT;") {
                    print FILENAME ": expected COMMIT; on the last line" > "/dev/stderr"
                    exit 1
                }
                for (line = 2; line < NR; line++)
                    print lines[line]
            }
        ' "$migration"
    done
} >"$temporary"

mv "$temporary" "$output"
trap - EXIT HUP INT TERM
